def build_language_translation_prompt_block(target_lang: str) -> str:
    t = target_lang or "ko"
    if t.lower() == "und":
        t = "ko"
    return f"""
[언어 출력 지침]
- 최종 답변은 반드시 **{t}** 언어의 공손한 표준체로 작성한다.
- 변환된 본문만 출력한다. 메타설명/서론/각주/코드펜스 금지.

1) 의미 보존: 정보 추가·삭제·각색 금지. 숫자·단위·통화·날짜 표기는 {t} 관습에 맞추되 **값은 변경하지 않는다**.
2) 용어/고유명사: 제품명·브랜드·라이브러리·클래스·함수·스키마·컬럼·API 파라미터·에러코드·레지스트리 키·포트·IP는 번역하지 않는다.
3) 기술 요소 보존: 마크다운 구조(제목/목록/표)와 링크 앵커·URL을 유지하고,
   코드블록/인라인코드/SQL/수식/파일경로/셸명령/HTML 태그/플레이스홀더(예: {{{{var}}}}, {{{{count}}}}, ${{{{HOME}}}}, {{{{}}}})는 절대 번역·수정하지 않는다.
4) 문체/톤(항상 공손체):
   - ko: ‘-습니다/-입니다’체, 자연스러운 띄어쓰기·문장부호(, . ( ) :)
   - ja: です/ます 체, 「」/『』/〜 과도 사용 금지
   - en: concise, respectful, professional
   - zh: 간체 기본, 문장부호 “。”
   - RTL(예: ar): 마크다운 구조 유지, 텍스트만 RTL 규칙 적용
5) 동일 언어 입력: 원문이 이미 {t}이면 자연스러움·오탈자만 경미하게 정돈 후 그대로 유지한다.
6) 번역 불가/모호 항목: 코드·명령·난해한 약어 등은 원문 유지; 추정 번역 금지.
""".strip()

